#!/usr/bin/env node
// docs/guide.md → src/lib/guide-content.ts (the in-app guide: (!) button and /guide).
// Usage: npm run guide
// Rules: `## ` = tab, `### ` = heading, **bold** = UI button chip, ==text== = highlight,
// a paragraph that is only **bold** = sub-heading, a paragraph starting **N.** = numbered step,
// `> ` = warning callout, ![](../public/guide/x.webp) = screenshot (served from /guide/x.webp).
// Code spans/blocks are escaped, so the generated HTML is safe to inject (committed static content).
import fs from "node:fs";
import path from "node:path";

const root = path.resolve(path.dirname(new URL(import.meta.url).pathname), "..");
const SRC = path.join(root, "docs/guide.md");
const OUT = path.join(root, "src/lib/guide-content.ts");

const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;").replace(/"/g, "&quot;").replace(/'/g, "&#x27;");
const URL_RE = /https?:\/\/[^\s<>()`]+[^\s<>()`.,)]/g;

function inline(s) {
  return s.split(/(`[^`]+`)/).map((p) => {
    if (p.length >= 2 && p.startsWith("`") && p.endsWith("`")) return `<code>${esc(p.slice(1, -1))}</code>`;
    return esc(p)
      .replace(/\*\*(.+?)\*\*/g, '<span class="ui">$1</span>')
      .replace(/==(.+?)==/g, "<mark>$1</mark>")
      .replace(URL_RE, (u) => `<a href="${u}" target="_blank" rel="noreferrer">${u}</a>`);
  }).join("");
}

function figure(src) {
  const name = path.basename(src);
  const w = `/guide/${name}`;
  return `<figure><a href="${w}" target="_blank" rel="noreferrer" title="원본 크기로 보기"><img src="${w}" alt="" loading="lazy" /></a></figure>`;
}

const splitRow = (line) => line.trim().replace(/^\||\|$/g, "").split(/(?<!\\)\|/).map((c) => c.trim().replace(/\\\|/g, "|"));

function render(lines) {
  const out = [];
  let para = [];
  const flush = () => {
    if (!para.length) return;
    const text = para.map((x) => x.trim()).join(" ");
    para = [];
    let m = /^\*\*([^*]+)\*\*$/.exec(text);
    if (m) return out.push(`<h4>${inline(m[1])}</h4>`);
    m = /^\*\*(\d+)\.\*\*\s*(.*)$/.exec(text);
    if (m) return out.push(`<p class="step"><span class="n">${m[1]}</span><span>${inline(m[2])}</span></p>`);
    out.push(`<p>${inline(text)}</p>`);
  };
  for (let i = 0; i < lines.length; ) {
    const s = lines[i].trim();
    if (!s || s === "---") { flush(); i++; continue; }
    if (s.startsWith("```")) {
      flush();
      const buf = [];
      for (i++; i < lines.length && !lines[i].trim().startsWith("```"); i++) buf.push(lines[i]);
      out.push(`<pre><code>${esc(buf.join("\n"))}</code></pre>`);
      i++; continue;
    }
    let m = /^!\[[^\]]*\]\(([^)]+)\)$/.exec(s);
    if (m) { flush(); out.push(figure(m[1])); i++; continue; }
    if (s.startsWith("### ")) { flush(); out.push(`<h3>${inline(s.slice(4))}</h3>`); i++; continue; }
    if (s.startsWith("> ")) { flush(); out.push(`<blockquote>${inline(s.slice(2))}</blockquote>`); i++; continue; }
    if (s.startsWith("- ")) {
      flush();
      const items = [];
      for (; i < lines.length && lines[i].trim().startsWith("- "); i++) items.push(`<li>${inline(lines[i].trim().slice(2))}</li>`);
      out.push(`<ul>${items.join("")}</ul>`); continue;
    }
    if (s.startsWith("|")) {
      flush();
      const rows = [];
      for (; i < lines.length && lines[i].trim().startsWith("|"); i++) rows.push(lines[i]);
      const th = splitRow(rows[0]).map((c) => `<th>${inline(c)}</th>`).join("");
      const tb = rows.slice(2).map((r) => `<tr>${splitRow(r).map((c) => `<td>${inline(c)}</td>`).join("")}</tr>`).join("");
      out.push(`<div class='tableWrap'><table><thead><tr>${th}</tr></thead><tbody>${tb}</tbody></table></div>`); continue;
    }
    para.push(lines[i]); i++;
  }
  flush();
  return out.join("");
}

const md = fs.readFileSync(SRC, "utf8");
if (!md.startsWith("# ")) throw new Error("docs/guide.md must start with a '# ' title");
const body = md.split("\n").slice(1).join("\n");
const parts = body.split(/^## (.+)$/m);
const intro = parts[0];
const sections = [];
for (let k = 1; k < parts.length; k += 2) {
  const text = (k === 1 ? intro + "\n\n" : "") + parts[k + 1];
  sections.push({ id: `s${(k + 1) / 2}`, title: parts[k].trim(), html: render(text.split("\n")) });
}
const missing = [...md.matchAll(/!\[[^\]]*\]\(([^)]+)\)/g)]
  .map((m) => path.join(root, "public/guide", path.basename(m[1])))
  .filter((f) => !fs.existsSync(f));
if (missing.length) console.warn(`missing screenshots (${missing.length}):\n  ${missing.map((f) => path.relative(root, f)).join("\n  ")}`);

const updated = new Date(fs.statSync(SRC).mtime).toISOString().slice(0, 10);
const ts = [
  "// Generated by `npm run guide` from docs/guide.md — do not edit by hand.",
  "",
  "export type GuideSection = { id: string; title: string; html: string };",
  "",
  `export const GUIDE_UPDATED_AT = ${JSON.stringify(updated)};`,
  "",
  "export const GUIDE_SECTIONS: GuideSection[] = [",
  ...sections.flatMap((s) => ["  {", `    id: ${JSON.stringify(s.id)},`, `    title: ${JSON.stringify(s.title)},`, `    html: ${JSON.stringify(s.html)},`, "  },"]),
  "];",
  "",
].join("\n");
fs.writeFileSync(OUT, ts);
console.log(`${sections.length} sections → ${path.relative(root, OUT)}`);
